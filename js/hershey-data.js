function makeArchitectGlyphs() {
  const g = makeSimplexGlyphs();

  // Exaggerated crossbars & confident straight lines
  g['A'] = { width: 19, strokes: [ [[2, 0], [9, -24], [17, 0]], [[1, -9], [18, -9]] ] };
  g['B'] = { width: 17, strokes: [ [[3, 0], [3, -24]], [[3, -24], [12, -24], [15, -20], [13, -14], [3, -14]], [[3, -14], [13, -14], [16, -8], [14, 0], [1, 0]] ] };
  g['C'] = { width: 17, strokes: [ [[16, -21], [12, -24], [5, -24], [2, -18], [2, -6], [6, 0], [14, 0], [17, -5]] ] };
  g['E'] = { width: 16, strokes: [ [[3, 0], [3, -24], [16, -24]], [[3, -14], [12, -14]], [[3, 0], [16, 0]] ] };
  g['F'] = { width: 16, strokes: [ [[3, 0], [3, -24], [16, -24]], [[3, -14], [12, -14]] ] };
  g['H'] = { width: 19, strokes: [ [[3, 0], [3, -24]], [[16, 0], [16, -24]], [[0, -13], [19, -13]] ] };
  g['K'] = { width: 18, strokes: [ [[3, 0], [3, -24]], [[17, -24], [3, -12]], [[7, -14], [17, 0]] ] };
  g['R'] = { width: 18, strokes: [ [[3, 0], [3, -24], [12, -24], [16, -19], [14, -13], [3, -13]], [[9, -13], [17, 0]] ] };

  // Lowercase as small-caps with distinctive drafting charm
  const smallCaps = ['a','b','c','d','e','f','g','h','i','j','k','l','m','n','o','p','q','r','s','t','u','v','w','x','y','z'];
  smallCaps.forEach(char => {
    const upper = char.toUpperCase();
    if (g[upper]) {
      const uGlyph = g[upper];
      const scaledStrokes = uGlyph.strokes.map(str => 
        str.map(pt => [pt[0] * 0.8, pt[1] * 0.75])
      );
      g[char] = {
        width: Math.round(uGlyph.width * 0.8),
        strokes: scaledStrokes
      };
    }
  });

  return g;
}

// -------------------------------------------------------------
// 3. Quick Jot / Fast Note (Energetic slanted everyday notes)
// -------------------------------------------------------------
function makeQuickNoteGlyphs() {
  const g = makeCasualCursiveGlyphs();

  // Apply quick slant (~16 deg) and faster angular strokes
  const slantFactor = 0.28;
  for (const k in g) {
    const glyph = g[k];
    glyph.strokes = glyph.strokes.map(stroke => 
      stroke.map(pt => [pt[0] - pt[1] * slantFactor, pt[1]])
    );
    glyph.width = Math.round(glyph.width * 1.05);
  }

  return g;
}


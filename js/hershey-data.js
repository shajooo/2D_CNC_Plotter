/**
 * Vector Glyph definitions for Hershey and Handwriting Fonts
 * Scaled around standard 32-unit height box (baseline y=0, ascenders up to -24, descenders down to +8).
 * Includes 6 distinct authentic handwriting styles:
 * 1. Casual Cursive (hand_casual)
 * 2. Architect / Drafting Hand (hand_architect)
 * 3. Quick Jot / Fast Note (hand_quicknote)
 * 4. Fountain Pen Calligraphy (hand_fountain)
 * 5. Organic Hand-Print (hand_organic)
 * 6. Neat School Hand (hand_school)
 */

// Helper to clone glyph dictionary
function cloneGlyphs(source) {
  const target = {};
  for (const k in source) {
    target[k] = JSON.parse(JSON.stringify(source[k]));
  }
  return target;
}

